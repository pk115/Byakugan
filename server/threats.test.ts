import {mkdtempSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {it,expect} from "vitest";
process.env.SUPAPULSE_DATA_DIR=mkdtempSync(join(tmpdir(),"byakugan-threats-"));
const {db}=await import("./database.js");
const {ingestLogs}=await import("./log-events.js");
const {threatOverview}=await import("./threats.js");
const {evaluateThreatRules,resolveThreatCase,caseJourney}=await import("./threat-rules.js");
const {threatPolicy,excepted}=await import("./threat-policy.js");
it("creates one IDS case per sensor/IP/signature and counts only explicit block outcomes",()=>{
  const id=Number(db.prepare("INSERT INTO agents(name,token_hash) VALUES('sensor','sensor')").run().lastInsertRowid);
  const now=new Date('2026-11-12T01:00:00Z');
  const events=['detected','blocked'].map(result=>({source:'suricata',event:'IDS_ALERT',timestamp:now.toISOString(),srcIp:'192.0.2.30',result,severity:'critical' as const,details:{signature_id:123,dst_ip:'10.0.0.5'}}));
  ingestLogs(id,events);expect(evaluateThreatRules(id,now)).toHaveLength(1);expect(evaluateThreatRules(id,now)).toEqual([]);
  expect(threatOverview({agentId:id}).summary).toMatchObject({events:2,blocked:1});
  db.prepare('DELETE FROM agents WHERE id=?').run(id);
});
it("reopens acknowledged IDS cases only on severity escalation and includes related evidence",()=>{
  const id=Number(db.prepare("INSERT INTO agents(name,token_hash) VALUES('escalate','escalate')").run().lastInsertRowid);
  const now=new Date('2026-11-12T01:00:00Z');
  const event={source:'suricata',event:'IDS_ALERT',timestamp:now.toISOString(),srcIp:'192.0.2.31',result:'detected',severity:'warning' as const,details:{signature_id:55}};
  ingestLogs(id,[event]);const [finding]=evaluateThreatRules(id,now);
  db.prepare("UPDATE compliance_findings SET status='ACKNOWLEDGED' WHERE id=?").run(finding);
  ingestLogs(id,[{...event,severity:'critical',details:{signature_id:55,sequence:2}}]);
  expect(evaluateThreatRules(id,now)).toEqual([finding]);
  expect(db.prepare('SELECT status,severity FROM compliance_findings WHERE id=?').get(finding)).toEqual({status:'OPEN',severity:'CRITICAL'});
  ingestLogs(id,[{...event,event:'LOGIN_SUCCESS',timestamp:new Date(+now+60000).toISOString(),severity:'info',details:{}}]);
  expect(caseJourney(finding)?.events).toHaveLength(3);
  db.prepare('DELETE FROM agents WHERE id=?').run(id);
});
it("applies thresholds and expiring exceptions without deleting evidence",()=>{
  const id=Number(db.prepare("INSERT INTO agents(name,token_hash) VALUES('ports','ports')").run().lastInsertRowid);
  const now=new Date('2026-11-12T01:00:00Z'),policy={...threatPolicy(),portThreshold:3,notifications:true,exceptions:[{ip:'192.0.2.2',agentId:id,reason:'Authorized test source',expiresAt:'2026-11-12T02:00:00.000Z'}]};
  db.prepare("INSERT INTO app_settings(key,value) VALUES('threat_policy',?)").run(JSON.stringify(policy));
  ingestLogs(id,[22,80,443].map(port=>({source:'firewall',event:'FIREWALL_DENY',timestamp:now.toISOString(),srcIp:'192.0.2.2',severity:'warning',details:{dst_port:port}})) as Parameters<typeof ingestLogs>[1]);
  expect(evaluateThreatRules(id,now)).toEqual([]);
  expect(excepted(policy,id,'192.0.2.2',new Date('2026-11-12T03:00:00Z'))).toBe(false);
  policy.exceptions=[];db.prepare("UPDATE app_settings SET value=? WHERE key='threat_policy'").run(JSON.stringify(policy));
  expect(evaluateThreatRules(id,now)).toHaveLength(1);
  expect(evaluateThreatRules(id,now)).toEqual([]);
  expect((db.prepare('SELECT COUNT(*) AS n FROM threat_notification_queue').get() as {n:number}).n).toBe(1);
  expect((db.prepare('SELECT COUNT(*) AS n FROM log_events WHERE agent_id=?').get(id) as {n:number}).n).toBe(3);
  db.prepare("DELETE FROM app_settings WHERE key='threat_policy'").run();db.prepare('DELETE FROM agents WHERE id=?').run(id);
});
it("groups cases by machine/IP/account, preserves acknowledgement and requires new evidence to reopen",()=>{
  const id=Number(db.prepare("INSERT INTO agents(name,token_hash) VALUES('rules','rules')").run().lastInsertRowid);
  const now=new Date('2026-11-12T01:00:00Z');
  const batch=(offset:number,n:number)=>Array.from({length:n},(_,i)=>({source:'host',event:'SSH_LOGIN_FAILED',timestamp:new Date(+now-(offset+i)*1000).toISOString(),actor:'root',srcIp:'192.0.2.9',severity:'warning' as const,details:{}}));
  ingestLogs(id,batch(0,10));const [finding]=evaluateThreatRules(id,now);expect(finding).toBeTruthy();
  db.prepare("UPDATE compliance_findings SET status='ACKNOWLEDGED' WHERE id=?").run(finding);
  expect(evaluateThreatRules(id,now)).toEqual([]);
  expect(db.prepare('SELECT status FROM compliance_findings WHERE id=?').get(finding)).toEqual({status:'ACKNOWLEDGED'});
  db.prepare("UPDATE compliance_findings SET status='RESOLVED' WHERE id=?").run(finding);resolveThreatCase(finding);
  expect(evaluateThreatRules(id,now)).toEqual([]);
  ingestLogs(id,batch(20,9));expect(evaluateThreatRules(id,now)).toEqual([]);
  ingestLogs(id,batch(29,1));expect(evaluateThreatRules(id,now)).toEqual([finding]);
  db.prepare('DELETE FROM agents WHERE id=?').run(id);
});
it("aggregates the complete filtered period, not one page, and includes silent agents in coverage",()=>{
  const a=Number(db.prepare("INSERT INTO agents(name,token_hash) VALUES('one','one')").run().lastInsertRowid);
  const b=Number(db.prepare("INSERT INTO agents(name,token_hash) VALUES('silent','two')").run().lastInsertRowid);
  ingestLogs(a,Array.from({length:105},(_,i)=>({source:"host",event:"LOGIN_FAILED",timestamp:"2026-11-12T00:00:00.000Z",srcIp:"192.0.2.1",actor:`u${i}`,severity:"warning",details:{}})) as Parameters<typeof ingestLogs>[1]);
  ingestLogs(a,[{source:"nginx",event:"HTTP_REQUEST",timestamp:"2026-11-12T00:00:00.000Z",severity:"error",details:{status:500}}]);
  const result=threatOverview({agentId:a,limit:1,from:"2026-11-12T00:00:00.000Z",to:"2026-11-12T23:59:59.000Z"});
  expect(result.summary).toEqual({events:105,ips:1,agents:1,blocked:0});
  expect(result.sources).toHaveLength(1);
  expect(result.coverage).toHaveLength(1);
  expect(threatOverview({agentId:b}).summary).toMatchObject({events:0});
  expect(threatOverview({}).coverage).toHaveLength(2);
  expect(threatOverview({srcIp:"192.0.2.2"}).summary).toMatchObject({events:0});
});
